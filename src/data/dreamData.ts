/** 基于梦境关键词推断 emoji（词库未命中时兜底），保证记录图标与梦内容一致 */
export function keywordDreamEmoji(dreamKeyword: string, fallback = '🌙'): string {
  if (!dreamKeyword) return fallback;
  const clean = dreamKeyword.replace(/^梦见/, '');
  for (const [re, emoji] of KEYWORD_EMOJI_MAP) {
    if (re.test(clean)) return emoji;
  }
  return fallback;
}
