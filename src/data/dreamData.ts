/**
 * 根据关键词匹配分类（用于日记趋势分析）
 */
export function matchCategory(keyword: string): DreamCategoryKey {
  const k = keyword.replace(/^梦见|^梦到/, '');
  for (const [cat, words] of Object.entries(CATEGORY_KEYWORDS)) {
    if (words.some(w => k && w.includes(k) || k.includes(w.replace('梦见', '')))) {
      return cat as DreamCategoryKey;
    }
  }
  return 'other';
}

