/** 扁平查找：城市名 → 经纬度（兼容旧 CITIES 接口） */
export function findCityByName(name: string): RegionCity | undefined {
  for (const prov of CHINA_REGIONS) {
    const c = prov.cities.find((c) => c.name === name);
    if (c) return c;
  }
  return undefined;
}

