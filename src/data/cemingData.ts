/** 测字整体运势签 */
export interface OmenResult {
  level: string;
  text: string;
}
export function buildOmen(tendencyWord: string, element: Element): OmenResult {
  const level = tendencyWord === '吉' ? '上上签' : tendencyWord === '平' ? '中平签' : '下下签';
  const t = TENDENCIES.find((x) => x.word === tendencyWord);
  const flow = t?.flow ?? '';
  const imagery = ELEMENT_IMAGERY[element];
  const text = `此字属${element}行，${imagery}；${flow}签曰「${level}」，宜顺势养气、修德聚运。`;
  return { level, text };
}
