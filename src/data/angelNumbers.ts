export interface AngelResult {
  /** 归一化后的数字串（如 '1111'） */
  raw: string;
  /** 命中的词条 key（如 '111'） */
  key: string;
  entry: AngelEntry;
  /** 是否全同数字（如 2222） */
  isRepDigit: boolean;
  /** 是否连续序列（如 1234、456） */
  isSequence: boolean;
  /** 各位数字（去重保序） */
  digits: number[];
}

/** 数字根：反复求和到个位（0 保持 0） */
function digitalRoot(n: number): number {
  if (n === 0) return 0;
  const r = n % 9;
  return r === 0 ? 9 : r;
}

/**
 * 解析天使数字。
 * 匹配优先级：精确命中 → 全同数字压到三位 → 连续序列 → 数字根对应的三位重复数。
 * 输入非法（无数字）返回 null。
 */
export function parseAngelNumber(input: string): AngelResult | null {
  const raw = (input || '').replace(/[^\d]/g, '');
  if (!raw) return null;

  const digits = [...new Set(raw.split('').map(Number))];
  const nums = raw.split('').map(Number);
  const isRepDigit = nums.length > 1 && nums.every((d) => d === nums[0]);
  const isSequence =
    nums.length >= 3 &&
    nums.every((d, i) => i === 0 || d === (nums[i - 1] + 1) % 10);

  let key: string | null = null;
  if (ANGEL_NUMBERS[raw]) key = raw;
  else if (isRepDigit) {
    const k = String(nums[0]).repeat(3);
    key = ANGEL_NUMBERS[k] ? k : null;
  } else if (!key && ANGEL_NUMBERS[raw.slice(0, 4)]) {
    key = raw.slice(0, 4);
  }
  if (!key) {
    const root = digitalRoot(nums.reduce((a, b) => a + b, 0));
    const k = String(root).repeat(3);
    key = ANGEL_NUMBERS[k] ? k : '111';
  }

  return { raw, key, entry: ANGEL_NUMBERS[key], isRepDigit, isSequence, digits };
}
